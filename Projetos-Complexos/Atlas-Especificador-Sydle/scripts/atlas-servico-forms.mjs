function sectionForServicoField(fieldId) {
  const comercial = [
    'atlas-srv-parceiro',
    'atlas-srv-produto-catalogo',
    'atlas-srv-complexidade',
    'atlas-srv-categoria-objeto',
    'atlas-srv-grupo',
    'atlas-srv-versao-catalogo',
  ]
  const tecnico = ['atlas-srv-qtde-hst-ust', 'atlas-srv-metrica']
  const precificacao = [
    'atlas-srv-valor-unitario',
    'atlas-srv-recorrencia',
    'atlas-srv-tipo-cobranca',
    'atlas-srv-custo-parceiro',
    'atlas-srv-markup',
    'atlas-srv-dist-parceiro',
    'atlas-srv-dist-mti',
  ]
  const codigos = [
    'atlas-srv-siag',
    'atlas-srv-protheus',
    'atlas-srv-universal',
    'atlas-srv-individualizado',
  ]
  const parceria = [
    'atlas-srv-status-parceria',
    'atlas-srv-data-atualizacao-preco',
    'atlas-srv-indice-reajuste',
    'atlas-srv-ultima-homologacao',
  ]
  if (comercial.includes(fieldId)) return 'sec-srv-comercial'
  if (tecnico.includes(fieldId)) return 'sec-srv-tecnico'
  if (precificacao.includes(fieldId)) return 'sec-srv-precificacao'
  if (codigos.includes(fieldId)) return 'sec-srv-codigos'
  if (parceria.includes(fieldId)) return 'sec-srv-parceria'
  return 'sec-srv-comercial'
}

