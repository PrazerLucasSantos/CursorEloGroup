function darRow(p) {
  return {
    'atlas-dar-numero': p.numero ?? '',
    'atlas-dar-valor': p.valor ?? 0,
    'atlas-dar-vencimento': p.vencimento ?? '',
    'atlas-dar-cnpj': p.cnpj ?? '',
    'atlas-dar-status': p.status ?? 'Emitido',
    'atlas-dar-observacao': p.obs ?? '',
  }
}

function nfRow(p) {
  const row = {
    'atlas-nf-numero': p.numero ?? '',
    'atlas-nf-pedido-venda': p.pedido ?? '',
    'atlas-nf-contrato': p.contrato ?? '',
    'atlas-nf-cliente': p.cliente ?? '',
    'atlas-nf-cnpj-destinatario': p.cnpj ?? '',
    'atlas-nf-data-emissao': p.emissao ?? '',
    'atlas-nf-valor': p.valor ?? 0,
    'atlas-nf-status': p.status ?? 'Disponível no portal',
    'atlas-nf-protheus-identificada': p.protheus === false ? 'false' : 'true',
    'atlas-nf-email-notificado': p.emailNotificado === true ? 'true' : 'false',
    'atlas-nf-data-portal': p.dataPortal ?? '',
    'atlas-nf-cliente-informou-pagamento': p.informouPagamento === true ? 'true' : 'false',
    'atlas-nf-comprovante-dar': p.comprovante ?? '',
    'atlas-nf-link-download': p.link ?? 'atlas.mti.mt.gov.br/faturas',
  }
  if (p.dar) {
    row.emb_dar_vinculado = [darRow(p.dar)]
  }
  return row
}

function usuarioParceiroRow(p) {
  return {
    'atlas-upar-nome': p.nome ?? '',
    'atlas-upar-cnpj': p.cnpj ?? '',
    'atlas-upar-classe-tributaria': p.classe ?? 'Simples Nacional',
    'atlas-upar-impostos-sugeridos': p.impostos ?? '',
    'atlas-upar-tributos-mt': p.tributosMt ?? '',
    'atlas-upar-tributos-fora-mt': p.tributosFora ?? '',
    'atlas-upar-selo-gestor': p.selo ?? 'Pendente atestação',
    'atlas-upar-gestor-atestou': p.gestor ?? '',
    'atlas-upar-data-atestacao': p.dataAtestacao ?? '',
    'atlas-upar-observacao-gestor': p.obsGestor ?? '',
    ...(p.docs ? { [EMB_DOCS_ISENCAO]: p.docs } : {}),
  }
}

