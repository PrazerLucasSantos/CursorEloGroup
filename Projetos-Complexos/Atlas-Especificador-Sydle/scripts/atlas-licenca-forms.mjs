function codigoAtlasLicenca(p) {
  if (p.codigoAtlas) return p.codigoAtlas
  const siag = (p.siag ?? '').replace(/\s/g, '')
  return siag ? `ATLAS-LIC-${siag}` : ''
}

function licencaRow(p) {
  return {
    'atlas-lic-codigo-atlas': codigoAtlasLicenca(p),
    'atlas-lic-parceiro': p.parceiro,
    'atlas-lic-objeto-comercial': p.objeto,
    'atlas-lic-produto-catalogo': p.produto,
    'atlas-lic-metrica': p.metrica ?? 'USN',
    'atlas-lic-valor-unitario': p.valor ?? 0,
    'atlas-lic-versao-catalogo': p.versao ?? '1.0',
    'atlas-lic-part-number': p.partNumber ?? '',
    'atlas-lic-grupo': p.grupo ?? 'SaaS',
    'atlas-lic-recorrencia': p.recorrencia ?? 'Sob Demanda',
    'atlas-lic-modelo-venda': p.modeloVenda ?? 'SaaS',
    'atlas-lic-custo-parceiro': p.custoParceiro ?? 0,
    'atlas-lic-markup': p.markup ?? 1,
    'atlas-lic-dist-parceiro': p.distParceiro ?? 0,
    'atlas-lic-dist-mti': p.distMti ?? 0,
    'atlas-lic-vigencia': p.vigencia ?? '12 Meses',
    'atlas-lic-siag': p.siag ?? '',
    'atlas-lic-protheus': p.protheus ?? '',
    'atlas-lic-universal': p.universal ?? 'Não',
    'atlas-lic-individualizado': p.individualizado ?? 'Não',
    'atlas-lic-status-parceria': p.statusParceria ?? 'homologado',
    'atlas-lic-data-atualizacao-preco': p.dataAtualizacaoPreco ?? '',
    'atlas-lic-indice-reajuste': p.indiceReajuste ?? '',
    'atlas-lic-ultima-homologacao': p.ultimaHomologacao ?? '',
  }
}

