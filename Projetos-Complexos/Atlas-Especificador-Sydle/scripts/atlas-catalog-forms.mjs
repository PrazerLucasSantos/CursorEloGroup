export function refField(id, label, linkedFormId, opts = {}) {
  return {
    id,
    label,
    type: 'reference',
    linkedFormId,
    size: opts.size ?? 'medium',
    readOnly: false,
    required: opts.required ?? true,
    multiple: opts.multiple ?? false,
    relevance: opts.relevance ?? 'common',
    spec:
      opts.spec ??
      'Referência ao cadastro em «Parâmetros de domínio». Inclua novos valores na tabela mestre antes de usar no produto.',
  }
}

