function codigoAtlasProduto(p) {
  if (p.codigoAtlas) return p.codigoAtlas
  const siag = (p.siag ?? '').replace(/\s/g, '')
  return siag ? `ATLAS-PRD-${siag}` : ''
}

export function produtoCadastroRow(p) {
  return {
    'atlas-pcad-codigo-atlas': codigoAtlasProduto(p),
    'atlas-pcad-siag': p.siag ?? '',
    'atlas-pcad-protheus': p.protheus ?? '',
    'atlas-pcad-descricao': p.descricao,
    'atlas-pcad-solucao': p.solucao,
    'atlas-pcad-metrica': p.metrica,
    'atlas-pcad-cobranca': p.cobranca,
    'atlas-pcad-valor-unitario': p.valor ?? 0,
    'atlas-pcad-fc': p.fcNome ?? (p.fc === 0.56 ? '0,56' : p.fc === 0.67 ? '0,67' : '1,00'),
    'atlas-pcad-focal-vendas': p.focalVendas ?? '',
    'atlas-pcad-focal-pos': p.focalPos ?? 'Todos',
    'atlas-pcad-unidade-dtic': p.unidade,
    'atlas-pcad-parceiro': p.parceiro,
    'atlas-pcad-link-parceria': p.link ?? '',
    'atlas-prod-status': p.status ?? 'Vigente',
    'atlas-prod-exibir-vigentes': p.exibirVigentes !== false,
    'atlas-prod-ordem-grade': p.ordem ?? 0,
    'atlas-prod-observacoes': p.observacoes ?? '',
  }
}

